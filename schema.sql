-- Por isso, apenas a service_role pode aceder diretamente à API do Supabase.
-- Remover todas as políticas anteriores destas tabelas elimina políticas anon
-- permissivas de versões anteriores e torna a reaplicação determinística.
DO $$
DECLARE
    policy_row RECORD;
BEGIN
    FOR policy_row IN
        SELECT schemaname, tablename, policyname
        FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename IN (
              'users', 'auth_challenges', 'auth_code_lockouts', 'business_info',
              'contacts', 'messages', 'conversion_requests', 'response_variants',
              'email_integrations',
              'processed_email_messages', 'email_threads', 'subscriptions',
              'website_integrations'
          )
    LOOP
        EXECUTE format(
            'DROP POLICY IF EXISTS %I ON %I.%I',
            policy_row.policyname, policy_row.schemaname, policy_row.tablename
        );
    END LOOP;
END;
$$;


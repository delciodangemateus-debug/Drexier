import json

with open("frontend/i18n.js", "r", encoding="utf-8") as f:
    content = f.read()

# Generate extra translations code to insert
en_entries = "\\n".join([f'  {json.dumps(pt)}: {json.dumps(en)},' for pt, en in new_pairs])
pt_entries = "\\n".join([f'  {json.dumps(en)}: {json.dumps(pt)},' for pt, en in new_pairs])

# Insert into translationsEn before "const translationsPt"
if "const translationsPt" in content:
    idx_pt = content.find("const translationsPt")
    # find the }; preceding it
    brace_idx = content.rfind("};", 0, idx_pt)
    content = content[:brace_idx] + en_entries + "\\n" + content[brace_idx:]

# Insert into translationsPt before "function translateText"
if "function translateText" in content:
    idx_fn = content.find("function translateText")
    brace_idx2 = content.rfind("};", 0, idx_fn)
    content = content[:brace_idx2] + pt_entries + "\\n" + content[brace_idx2:]

with open("frontend/i18n.js", "w", encoding="utf-8") as f:
    f.write(content)

print(f"i18n.js successfully updated with {len(new_pairs)} bilingual pairs.")

-- 1. Extensões úteis do PostgreSQL
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 2. Função de gatilho para atualização automática da coluna updated_at
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = TIMEZONE('utc'::text, NOW());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ==============================================================================
-- TABELA 1: USERS (Utilizadores e Contas do Sistema)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    business_type TEXT NOT NULL,
    business_description TEXT DEFAULT '',
    language TEXT NOT NULL DEFAULT 'Português',
    agent_instructions TEXT DEFAULT '',
    mandatory_responses JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT TIMEZONE('utc'::text, NOW()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT TIMEZONE('utc'::text, NOW())
);

CREATE TRIGGER set_timestamp_users
BEFORE UPDATE ON public.users
FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

COMMENT ON TABLE public.users IS 'Armazena as contas dos proprietários de empresas do Drexier.';

-- ==============================================================================
-- TABELA 2: BUSINESS_INFO (Base de Conhecimento e Treinamento da IA)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.business_info (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    kind TEXT NOT NULL,
    title TEXT NOT NULL,
    content TEXT NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT TIMEZONE('utc'::text, NOW()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT TIMEZONE('utc'::text, NOW())
);

CREATE INDEX IF NOT EXISTS idx_business_info_user_id ON public.business_info(user_id);
CREATE INDEX IF NOT EXISTS idx_business_info_kind ON public.business_info(kind);

CREATE TRIGGER set_timestamp_business_info
BEFORE UPDATE ON public.business_info
FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

COMMENT ON TABLE public.business_info IS 'Tópicos, preços, horários e regulamentos para treino da IA Drexier.';

-- ==============================================================================
-- TABELA 3: CONTACTS (Clientes e Interlocutores)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.contacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    name TEXT NOT NULL DEFAULT '',
    contact_key TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT TIMEZONE('utc'::text, NOW()),
    last_message_at TIMESTAMPTZ,
    CONSTRAINT unique_user_contact UNIQUE (user_id, contact_key)
);

CREATE INDEX IF NOT EXISTS idx_contacts_user_id ON public.contacts(user_id);
CREATE INDEX IF NOT EXISTS idx_contacts_contact_key ON public.contacts(contact_key);
CREATE INDEX IF NOT EXISTS idx_contacts_last_message_at ON public.contacts(last_message_at DESC);

COMMENT ON TABLE public.contacts IS 'Clientes ou contactos que enviaram mensagens para a conta da empresa.';

-- ==============================================================================
-- TABELA 4: MESSAGES (Histórico de Conversas e Mensagens)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    contact_id BIGINT NOT NULL REFERENCES public.contacts(id) ON DELETE CASCADE,
    sender TEXT NOT NULL CHECK(sender IN ('customer', 'agent', 'owner')),
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT TIMEZONE('utc'::text, NOW())
);

CREATE INDEX IF NOT EXISTS idx_messages_user_id ON public.messages(user_id);
CREATE INDEX IF NOT EXISTS idx_messages_contact_id ON public.messages(contact_id);
CREATE INDEX IF NOT EXISTS idx_messages_created_at ON public.messages(created_at ASC);

COMMENT ON TABLE public.messages IS 'Histórico cronológico de trocas de mensagens entre cliente, agente IA e proprietário.';

-- ==============================================================================
-- TABELA 5: CONVERSION_REQUESTS (Pedidos de Compra, Marcações e Validações)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.conversion_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    contact_id BIGINT NOT NULL REFERENCES public.contacts(id) ON DELETE CASCADE,
    request_type TEXT NOT NULL,
    details TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT TIMEZONE('utc'::text, NOW()),
